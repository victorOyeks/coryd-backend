package org.coryd.identity.dto;

import jakarta.validation.constraints.Size;
import org.coryd.common.enums.DevicePlatform;

/**
 * Optional device identification sent alongside sign-in, so the session that comes back is bound
 * to the handset that asked for it.
 *
 * <p>Optional on purpose: clients that predate device binding keep working and simply get an
 * unbound session, exactly as before. New clients - in particular any client offering fingerprint
 * sign-in - should always send it, because an unbound refresh token sitting behind a fingerprint
 * is a thirty-day credential that works from anywhere.
 *
 * @param deviceId   stable per install, generated by the client. A random UUID in the app's own
 *                   storage. Never the IMEI or advertising id - those are privileged, and the
 *                   binding does not need them.
 * @param deviceName what the user will see on the devices screen, e.g. "Victor's iPhone".
 */
public record DeviceInfo(
        @Size(max = 100) String deviceId,
        @Size(max = 120) String deviceName,
        DevicePlatform platform
) {
    public boolean isPresent() {
        return deviceId != null && !deviceId.isBlank();
    }
}
